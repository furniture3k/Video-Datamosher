import type { MoshCodec } from './bitstream';

export type FrameType = 'I' | 'P' | 'B' | 'S' | '?';

/** Tag describing what the mosh engine did to a frame (drives the frame strip colours). */
export type FrameTag = 'orig' | 'dup' | 'glitch' | 'moved' | 'spliced' | 'replaced';

export interface Frame {
  data: Uint8Array;
  type: FrameType;
  /** index of the source frame in the prepared (un-moshed) stream */
  src: number;
  tag: FrameTag;
  payloadStart: number;
}

export type ClipSource =
  | { kind: 'file'; fileId: string; name: string; mime: string; isImage: boolean; ext: string }
  | { kind: 'generator'; generator: string; name: string };

export type FitMode = 'fit' | 'fill' | 'stretch';

/** A file (or generator) in the media library. The same media can be used by many clips. */
export interface MediaItem {
  id: string;
  source: ClipSource;
  /** full source duration (s); stills get a long nominal duration */
  duration: number;
  width: number;
  height: number;
  fps: number;
  hasAudio: boolean;
  hasVideo: boolean;
  thumb?: string;
}

export type TransitionType =
  | 'dissolve'
  | 'dip'
  | 'dipwhite'
  | 'wipeleft'
  | 'wiperight'
  | 'wipeup'
  | 'wipedown'
  | 'slideleft'
  | 'slideright'
  | 'circleopen'
  | 'pixelize'
  | 'melt'
  | 'bloom'
  | 'glitch'
  | 'stutter'
  | 'liquid';

export interface Transition {
  type: TransitionType;
  /** seconds */
  duration: number;
  /** 0..1, how hard mosh transitions hit */
  intensity: number;
}

/** A clip on the timeline. */
export interface Clip {
  id: string;
  mediaId: string;
  /** 'v1' (the magnetic main video track) or an audio track id */
  track: string;
  /** timeline start in seconds (audio tracks only; video clips follow each other) */
  start: number;
  /** trim points in source seconds */
  in: number;
  out: number;
  speed: number;
  reverse: boolean;
  fit: FitMode;
  volume: number;
  /** video clips: their own sound is muted (or detached to an audio track) */
  muted: boolean;
  /** audio fades, seconds */
  fadeIn: number;
  fadeOut: number;
  /** video clips: transition from the previous clip into this one */
  transition?: Transition;
}

export interface Track {
  id: string;
  kind: 'video' | 'audio';
  name: string;
  muted: boolean;
  solo: boolean;
  volume: number;
  /** audio follows the mosh (stutters with it) instead of playing clean */
  mosh: boolean;
}

export interface TextClip {
  id: string;
  text: string;
  start: number;
  duration: number;
  /** font size as a fraction of frame height */
  size: number;
  color: string;
  font: 'sans' | 'serif' | 'mono' | 'impact';
  bold: boolean;
  /** position of the text centre, 0..1 */
  x: number;
  y: number;
  align: 'left' | 'center' | 'right';
  shadow: boolean;
  box: boolean;
  fade: number;
  /** burn into the video before moshing so the text melts too */
  moshed: boolean;
}

export type Aspect = 'auto' | '16:9' | '4:3' | '1:1' | '9:16' | '4:5' | '21:9';

export interface EncoderSettings {
  codec: MoshCodec;
  width: number;
  aspect: Aspect;
  fps: number;
  /** qscale 1 (best) .. 31 (crunchy) */
  quality: number;
  /** keyframe interval in frames */
  gop: number;
  sceneCut: boolean;
  bframes: number;
  motionEst: 'zero' | 'epzs' | 'xone';
  meRange: number;
  mbd: 'simple' | 'bits' | 'rd';
  mv4: boolean;
  qpel: boolean;
  trellis: boolean;
  cmp: 'sad' | 'sse' | 'satd' | 'dct' | 'rd' | 'zero' | 'vsad' | 'nsse';
  keyAtCuts: boolean;
  /** extra forced keyframes (frame numbers) */
  keyMarkers: number[];
  previewWidth: number;
}

export interface DecoderSettings {
  guessMvs: boolean;
  deblock: boolean;
  favorInter: boolean;
  ignoreErrors: boolean;
  showAll: boolean;
}

export type AutoInterp = 'linear' | 'smooth' | 'step';
export type LfoShape = 'sine' | 'triangle' | 'square' | 'saw' | 'random' | 'noise';

export type Automation =
  | { kind: 'curve'; points: [number, number][]; interp: AutoInterp }
  | { kind: 'lfo'; shape: LfoShape; rate: number; min: number; max: number; phase: number };

export type ParamValue = number | boolean | string;

export interface EffectInstance {
  id: string;
  type: string;
  name?: string;
  enabled: boolean;
  solo: boolean;
  /** timeline-frame range [start, end) */
  start: number;
  end: number;
  /** generated by a transition (not stored in the project) */
  transition?: string;
  seed: number;
  params: Record<string, ParamValue>;
  auto: Record<string, Automation>;
  locks: string[];
}

export interface AudioSettings {
  mode: 'follow' | 'original';
  crossfade: boolean;
  volume: number;
  bitcrush: number;
  downsample: number;
  glitch: number;
  reverseChunks: number;
}

export interface Project {
  version: 2;
  name: string;
  media: MediaItem[];
  clips: Clip[];
  tracks: Track[];
  texts: TextClip[];
  encoder: EncoderSettings;
  decoder: DecoderSettings;
  effects: EffectInstance[];
  audio: AudioSettings;
  globalSeed: number;
}

