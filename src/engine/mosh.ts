// Pure mosh core: prepared AVI -> frames -> effect stack -> moshed AVI.
import { parseAvi, writeAvi, writeAviParts, type AviInfo } from './avi';
import { analyzeFrame, type MoshCodec } from './bitstream';
import { EFFECTS } from './effects';
import { inRange, isMotion, posOf, copy } from './effects/util';
import { hashSeed, makeRng } from './rng';
import type { EffectInstance, Frame, Project } from './types';
import { transitionEffects } from './timeline';
import { withChaos } from './chaos';
import { bakeAudio, type MoshAudio } from './audiofx';

export interface Prepared {
  info: AviInfo;
  frames: Frame[];
}

export function framesFromAvi(buf: Uint8Array, codec: MoshCodec): Prepared {
  const { info, chunks } = parseAvi(buf);
  const frames = chunks.map((c, i): Frame => {
    const a = analyzeFrame(c.data, codec);
    return { data: c.data, type: a.type === '?' && c.keyframe ? 'I' : a.type, src: i, tag: 'orig', payloadStart: a.payloadStart };
  });
  return { info, frames };
}

/** Join separately prepared segments into one stream (each segment starts with a keyframe). */
export function concatPrepared(parts: Prepared[]): Prepared {
  if (parts.length === 1) return parts[0];
  const frames: Frame[] = [];
  for (const p of parts) for (const f of p.frames) frames.push({ ...f, src: frames.length });
  return { info: parts[0].info, frames };
}

/** Output length cap in the browser (10 minutes at 24 fps). */
export const MAX_OUTPUT_FRAMES = 14400;
/**
 * Output length cap in the desktop app (30 minutes at 24 fps). Exports keep the video on disk, but
 * the preview (decoded frames, soundtrack) is still held in memory, which is what limits length.
 */
export const MAX_OUTPUT_FRAMES_DESKTOP = 43200;
/** The cap in force; a safety net against runaway stacks (bloom on every frame x 200) eating all memory. */
export const limits = { maxOutputFrames: MAX_OUTPUT_FRAMES };

export function activeEffects(effects: EffectInstance[]): EffectInstance[] {
  const solo = effects.some((e) => e.solo && e.enabled);
  return effects.filter((e) => e.enabled && (!solo || e.solo) && EFFECTS[e.type]);
}

/** User effects plus the ones generated by mosh transitions (those run first). */
export function allEffects(project: Project): EffectInstance[] {
  return [...transitionEffects(project, project.encoder.fps), ...project.effects];
}

const bitstreamEffects = (project: Project) => activeEffects(allEffects(project)).filter((e) => EFFECTS[e.type].kind === 'bitstream');

function applyOne(frames: Frame[], inst: EffectInstance, prep: Prepared, project: Project, cuts: number[], audio?: MoshAudio): Frame[] {
  const e = bakeAudio(withChaos(inst, project.chaos), audio, project);
  const rng = makeRng(hashSeed(project.globalSeed, e.seed, e.id));
  const def = EFFECTS[e.type];
  if (def.kind !== 'bitstream') return frames;
  const out = def.apply(frames, e, { totalFrames: prep.frames.length, fps: project.encoder.fps, cuts, rng, source: prep.frames, audio: audio?.sources[audio.beatKey] });
  return def.retimes && e.params.timing !== 'stretch' ? fitRange(frames, out, e) : out;
}

/**
 * Fit an effect's output back into its range ("Keep length"): every frame it added replaces the
 * next frame after it (keyframes are kept: they still reset the picture), anything
 * left over is trimmed from the end of the range, and a range that lost frames is padded by
 * repeating its last motion. The frames in the range then take the range's timeline positions,
 * so output frame N is timeline frame N again.
 */
export function fitRange(input: Frame[], out: Frame[], e: Pick<EffectInstance, 'start' | 'end'>): Frame[] {
  const slots = input.filter((f) => inRange(f, e)).map(posOf);
  const n = slots.length;
  if (!n) return out;
  const orig = new Set(input);
  let res: Frame[] = out;
  const count = () => res.reduce((c, f) => c + (inRange(f, e) ? 1 : 0), 0);
  if (count() > n) {
    res = [];
    let debt = 0;
    // B-frames right after a dropped frame refer to it, so they go too
    let dropB = false;
    for (const f of out) {
      if (dropB && f.type === 'B' && orig.has(f)) {
        if (inRange(f, e)) debt = Math.max(0, debt - 1);
        continue;
      }
      if (inRange(f, e)) {
        if (!orig.has(f)) debt++;
        else if (debt > 0 && f.type !== 'I' && res.length > 0) {
          debt--;
          dropB = true;
          continue;
        }
      }
      dropB = false;
      res.push(f);
    }
    // still too long: trim from the end of the range
    for (let i = res.length - 1, extra = count() - n; i > 0 && extra > 0; i--)
      if (inRange(res[i], e)) {
        res.splice(i, 1);
        extra--;
      }
  }
  let have = count();
  if (have < n) {
    let last = -1;
    res.forEach((f, i) => inRange(f, e) && (last = i));
    const src = [...res.slice(0, last + 1)].reverse().find(isMotion) ?? res[Math.max(0, last)];
    if (src) {
      const pad: Frame[] = [];
      for (; have < n; have++) pad.push(copy(src, 'dup'));
      res = res === out ? res.slice() : res;
      res.splice(last + 1, 0, ...pad);
    }
  }
  // the range's frames take its timeline positions, in order
  const sorted = slots.slice().sort((a, b) => a - b);
  let k = 0;
  return res.map((f) => {
    if (!inRange(f, e) || k >= n) return f;
    const at = sorted[k++];
    return posOf(f) === at ? f : { ...f, at };
  });
}

function finishFrames(frames: Frame[], prep: Prepared): Frame[] {
  // The decoder needs a real keyframe (with headers) first.
  if (frames.length === 0 || frames[0].type !== 'I') frames.unshift(prep.frames[0]);
  if (frames.length > limits.maxOutputFrames) frames.length = limits.maxOutputFrames;
  return frames;
}

export function applyBitstream(prep: Prepared, project: Project, cuts: number[], audio?: MoshAudio): Frame[] {
  let frames = prep.frames.slice();
  for (const e of bitstreamEffects(project)) frames = applyOne(frames, e, prep, project, cuts, audio);
  return finishFrames(frames, prep);
}

/** Effects that rewrite the bytes of frames (the rest only reorder, repeat or drop them). */
export const EDITS_BYTES = new Set(['glitch']);

/**
 * applyBitstream for disk-backed frames: before each effect that edits bytes, `load` gets the
 * frames it may touch (those in its range) so their full payloads can be read in. Same result.
 */
export async function applyBitstreamDisk(prep: Prepared, project: Project, cuts: number[], load: (frames: Frame[]) => Promise<Map<Frame, Frame>>, audio?: MoshAudio): Promise<Frame[]> {
  let frames = prep.frames.slice();
  for (const e of bitstreamEffects(project)) {
    if (EDITS_BYTES.has(e.type)) {
      const touched = [...new Set(frames.filter((f) => f.size !== undefined && posOf(f) >= e.start && posOf(f) < e.end))];
      if (touched.length) {
        // loaded frames are ordinary in-memory frames: swap them in
        const loaded = await load(touched);
        frames = frames.map((f) => loaded.get(f) ?? f);
      }
    }
    frames = applyOne(frames, e, prep, project, cuts, audio);
  }
  return finishFrames(frames, prep);
}

export function writeMoshed(prep: Prepared, frames: Frame[]): Uint8Array {
  return writeAvi(
    prep.info,
    frames.map((f) => ({ data: f.data, keyframe: f.type === 'I' })),
  );
}

/** The moshed stream as a Blob (frame payloads are not copied into one big buffer). */
export function writeMoshedBlob(prep: Prepared, frames: Frame[]): Blob {
  return new Blob(
    writeAviParts(
      prep.info,
      frames.map((f) => ({ data: f.data, keyframe: f.type === 'I' })),
    ) as BlobPart[],
    { type: 'video/x-msvideo' },
  );
}
